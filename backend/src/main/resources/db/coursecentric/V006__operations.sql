-- Append-only business and security history. Never stores credentials, tokens or raw exam answers.
create table audit_events (
    id             uuid         primary key,
    occurred_at    timestamptz  not null,
    actor_id       uuid         references users (id),
    action         varchar(100) not null,
    aggregate_type varchar(50)  not null,
    aggregate_id   uuid,
    -- AuditOutcome code: 0 SUCCESS, 1 DENIED, 2 FAILURE.
    outcome        smallint     not null check (outcome between 0 and 2),
    metadata       jsonb        not null default '{}'
);

create index audit_events_aggregate_idx on audit_events (aggregate_type, aggregate_id, occurred_at);
create index audit_events_time_idx on audit_events (occurred_at);

-- Durable work inserted in the caller's transaction and claimed with FOR UPDATE SKIP LOCKED leases.
create table background_jobs (
    id                uuid          primary key,
    type              varchar(100)  not null,
    aggregate_id      uuid,
    deduplication_key varchar(200)  unique,
    payload           jsonb         not null default '{}',
    -- JobStatus code: 0 PENDING, 1 RUNNING, 2 SUCCEEDED, 3 FAILED.
    status            smallint      not null check (status between 0 and 3),
    attempts          integer       not null default 0 check (attempts >= 0),
    available_at      timestamptz   not null,
    lease_until       timestamptz,
    lease_token       uuid,
    last_error        varchar(2000),
    created_at        timestamptz   not null,
    updated_at        timestamptz   not null,
    completed_at      timestamptz
);

create index background_jobs_claim_idx on background_jobs (status, available_at);

create table notifications (
    id                uuid          primary key,
    recipient_id      uuid          not null references users (id),
    type              varchar(100)  not null,
    title             varchar(200)  not null,
    body              varchar(2000) not null default '',
    link              varchar(500),
    deduplication_key varchar(200)  unique,
    created_at        timestamptz   not null,
    read_at           timestamptz
);

create index notifications_recipient_idx on notifications (recipient_id, read_at, created_at desc);

-- CSV exports are generated by a job into private storage and downloadable only by the requesting course author,
-- whose authorship and active status are rechecked at generation and download.
create table report_exports (
    id                uuid         primary key,
    course_id         uuid         not null references courses (id),
    course_version_id uuid,
    requested_by      uuid         not null references users (id),
    -- ReportType code: 0 PROGRESS, 1 SCORES.
    type              smallint     not null check (type between 0 and 1),
    -- ExportStatus code: 0 PENDING, 1 READY, 2 FAILED.
    status            smallint     not null check (status between 0 and 2),
    storage_key       varchar(200) not null unique,
    created_at        timestamptz  not null,
    completed_at      timestamptz,
    foreign key (course_id, course_version_id) references course_versions (course_id, id)
);

create index report_exports_requester_idx on report_exports (requested_by, course_id, created_at desc);

-- Installation-wide maintenance switch used by backups and restores: ordinary mutations are refused and background
-- jobs are not claimed while it is on. Backup scripts toggle it with SQL so they need no application credentials.
create table system_state (
    id          smallint     primary key check (id = 1),
    maintenance boolean      not null default false,
    reason      varchar(200),
    updated_at  timestamptz  not null
);

